export type Copy = typeof en;

export function copy(lang: Lang): Copy {
  return lang === "es" ? es : en;
}

export function typeLabel(type: string, lang: Lang): string {
  const text = copy(lang);
  if (type === "turnover") return text.turnover;
  if (type === "on-request") return text.onRequestFreq;
  return text.recurring;
}

export function frequencyLabel(frequency: string, day: string, lang: Lang): string {
  const text = copy(lang);
  if (frequency === "weekly") return `${text.weekly} (${day})`;
  if (frequency === "biweekly") return `${text.biweekly} (${day})`;
  return text.onRequestFreq;
}
